create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 username text unique, display_name text, bio text, avatar_url text,
 created_at timestamptz not null default now()
);
create table if not exists public.posts (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 content text not null default '', image_url text,
 created_at timestamptz not null default now(),
 constraint post_has_content_or_image check (length(trim(content)) > 0 or image_url is not null)
);
create index if not exists posts_created_at_idx on public.posts(created_at desc);
create index if not exists posts_user_id_idx on public.posts(user_id);
create table if not exists public.communities (
 id bigint generated by default as identity primary key,
 name text not null, slug text not null unique, description text,
 created_at timestamptz not null default now()
);
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
 insert into public.profiles(id,username,display_name)
 values(new.id,nullif(new.raw_user_meta_data ->> 'username',''),
 coalesce(nullif(new.raw_user_meta_data ->> 'display_name',''),split_part(new.email,'@',1)))
 on conflict(id) do nothing;
 return new;
end; $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
